const dicts: Record<Lang, Dict> = { id, en, zh };

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
  tl: (v: LocalizedText | undefined) => string;
};
const I18nCtx = createContext<Ctx>({
  lang: "id",
  setLang: () => {},
  t: (k) => k,
  tl: (v) => v?.id ?? "",
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("id");
  useEffect(() => {
    const stored = typeof window !== "undefined" ? localStorage.getItem("lang") : null;
    if (stored === "id" || stored === "en" || stored === "zh") setLangState(stored);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("lang", l);
  };
  const t = (k: string) => dicts[lang][k] ?? k;
  const tl = (v: LocalizedText | undefined) => (v ? v[lang] ?? v.id : "");
  return <I18nCtx.Provider value={{ lang, setLang, t, tl }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
